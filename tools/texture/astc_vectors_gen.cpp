// Generates tests/gpu/texture/astc_vectors.txt with ARM's reference codec
// (astcenc, Apache-2.0) as oracle. Not part of the build: compile it against
// an astcenc checkout, see tools/texture/gen_astc_vectors.py.
//
// Every line: "<bw> <bh> <srgb> <block hex, 32 chars> <fnv1a64 of the decoded
// RGBA8 texels, 16 hex chars>". The blocks are own synthetic images encoded
// with astcenc (all footprints, several effort levels), random 128-bit
// blocks (mostly invalid -> error colour) and random void-extent blocks.
#include <astcenc.h>

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <random>
#include <set>
#include <string>
#include <vector>

namespace {

uint64_t fnv1a64(const uint8_t* p, size_t n) {
    uint64_t h = 0xcbf29ce484222325ull;
    for (size_t i = 0; i < n; ++i) {
        h ^= p[i];
        h *= 0x100000001b3ull;
    }
    return h;
}

astcenc_context* make_context(unsigned bw, unsigned bh, bool srgb, float quality, bool decompress_only) {
    astcenc_config cfg;
    const unsigned flags = decompress_only ? ASTCENC_FLG_DECOMPRESS_ONLY : ASTCENC_FLG_USE_DECODE_UNORM8;
    if (astcenc_config_init(srgb ? ASTCENC_PRF_LDR_SRGB : ASTCENC_PRF_LDR, bw, bh, 1, quality, flags, &cfg) !=
        ASTCENC_SUCCESS)
        std::abort();
    astcenc_context* ctx = nullptr;
    if (astcenc_context_alloc(&cfg, 1, &ctx) != ASTCENC_SUCCESS)
        std::abort();
    return ctx;
}

// Synthetic test image: gradients, hard edges, noise and varying alpha so the
// encoder picks many partitionings, endpoint modes and weight grids.
std::vector<uint8_t> make_image(unsigned w, unsigned h, unsigned kind, std::mt19937& rng) {
    std::vector<uint8_t> img(size_t(w) * h * 4);
    std::uniform_int_distribution<int> byte(0, 255);
    const int c0[4] = {byte(rng), byte(rng), byte(rng), byte(rng)};
    const int c1[4] = {byte(rng), byte(rng), byte(rng), byte(rng)};
    for (unsigned y = 0; y < h; ++y) {
        for (unsigned x = 0; x < w; ++x) {
            uint8_t* p = &img[(size_t(y) * w + x) * 4];
            for (int c = 0; c < 4; ++c) {
                int v = 0;
                switch (kind % 6) {
                case 0: v = c0[c] + (c1[c] - c0[c]) * int(x + y) / int(w + h); break;           // gradient
                case 1: v = ((x / 3 + y / 5) & 1) ? c0[c] : c1[c]; break;                        // edges
                case 2: v = byte(rng); break;                                                    // noise
                case 3: v = (c == 3) ? byte(rng) : c0[c] + int(16 * std::sin(x * 0.7 + c)); break;  // alpha noise
                case 4: v = (c < 3) ? c0[0] + int(x * 7) % 64 : 255; break;                     // grey ramp
                default: v = (x * x + y * y < w * h / 3) ? c0[c] : c1[c] + byte(rng) % 9; break;  // disc
                }
                p[c] = uint8_t(std::min(255, std::max(0, v)));
            }
        }
    }
    return img;
}

void emit(unsigned bw, unsigned bh, bool srgb, const uint8_t* block, astcenc_context* dec) {
    std::vector<uint8_t> out(size_t(bw) * bh * 4);
    void* slices[1] = {out.data()};
    astcenc_image image{bw, bh, 1, ASTCENC_TYPE_U8, slices};
    const astcenc_swizzle swz{ASTCENC_SWZ_R, ASTCENC_SWZ_G, ASTCENC_SWZ_B, ASTCENC_SWZ_A};
    if (astcenc_decompress_image(dec, block, 16, &image, &swz, 0) != ASTCENC_SUCCESS)
        std::abort();
    astcenc_decompress_reset(dec);
    std::printf("%u %u %d ", bw, bh, srgb ? 1 : 0);
    for (int i = 0; i < 16; ++i)
        std::printf("%02x", block[i]);
    std::printf(" %016llx\n", static_cast<unsigned long long>(fnv1a64(out.data(), out.size())));
}

}  // namespace

int main(int argc, char** argv) {
    const unsigned per_kind = argc > 1 ? unsigned(std::atoi(argv[1])) : 60;
    static const unsigned kFootprints[][2] = {{4, 4},  {5, 4},  {5, 5},  {6, 5},   {6, 6},   {8, 5},   {8, 6},
                                              {8, 8},  {10, 5}, {10, 6}, {10, 8}, {10, 10}, {12, 10}, {12, 12}};
    std::mt19937 rng(0x4c475021);  // fixed seed: reproducible file
    std::printf("# ASTC LDR decode vectors, generated by tools/texture/astc_vectors_gen.cpp (astcenc 5.3.0, seed fixed)\n");
    for (const auto& f : kFootprints) {
        const unsigned bw = f[0], bh = f[1];
        for (int srgb = 0; srgb < 2; ++srgb) {
            astcenc_context* dec = make_context(bw, bh, srgb, ASTCENC_PRE_FASTEST, true);
            // 1. Encoded synthetic images.
            std::set<std::string> seen;
            const float qualities[] = {ASTCENC_PRE_FASTEST, ASTCENC_PRE_MEDIUM, ASTCENC_PRE_THOROUGH};
            unsigned emitted = 0;
            for (unsigned kind = 0; emitted < per_kind * 2 && kind < 600; ++kind) {
                astcenc_context* enc = make_context(bw, bh, srgb, qualities[kind % 3], false);
                const unsigned w = bw * 2, h = bh * 2;
                std::vector<uint8_t> img = make_image(w, h, kind, rng);
                void* slices[1] = {img.data()};
                astcenc_image image{w, h, 1, ASTCENC_TYPE_U8, slices};
                const astcenc_swizzle swz{ASTCENC_SWZ_R, ASTCENC_SWZ_G, ASTCENC_SWZ_B, ASTCENC_SWZ_A};
                std::vector<uint8_t> blocks(4 * 16);
                if (astcenc_compress_image(enc, &image, &swz, blocks.data(), blocks.size(), 0) != ASTCENC_SUCCESS)
                    std::abort();
                astcenc_context_free(enc);
                for (unsigned i = 0; i < 4 && emitted < per_kind * 2; ++i) {
                    const std::string key(reinterpret_cast<const char*>(&blocks[i * 16]), 16);
                    if (!seen.insert(key).second)
                        continue;
                    emit(bw, bh, srgb, &blocks[i * 16], dec);
                    ++emitted;
                }
            }
            // 2. Random blocks; half of them with a random block mode taken
            // from the valid range of an encoded block's low bits.
            std::uniform_int_distribution<int> byte(0, 255);
            for (unsigned i = 0; i < per_kind; ++i) {
                uint8_t blk[16];
                for (auto& b : blk)
                    b = uint8_t(byte(rng));
                emit(bw, bh, srgb, blk, dec);
            }
            // 3. Void-extent blocks (LDR and HDR flag, valid and invalid coordinates).
            for (unsigned i = 0; i < per_kind / 6 + 2; ++i) {
                uint8_t blk[16];
                for (auto& b : blk)
                    b = uint8_t(byte(rng));
                blk[0] = 0xFC;
                blk[1] = uint8_t((blk[1] & ~0x01) | 0x01);  // bit 8 = 1 (mode 0x1FC)
                if (i % 2 == 0) {
                    blk[1] = uint8_t((blk[1] & 0x01) | 0x0C | 0xF0);  // bits 10,11 = 1, HDR bit 9 = 0
                    blk[1] &= uint8_t(~0x02);
                    for (int k = 2; k < 8; ++k)
                        blk[k] = 0xFF;  // all-ones coordinates
                }
                emit(bw, bh, srgb, blk, dec);
            }
            astcenc_context_free(dec);
        }
    }
    return 0;
}
