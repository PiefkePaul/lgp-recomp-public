#!/usr/bin/env python3
"""Test vectors for the BCn decoder (gpu/texture/bc.hpp, P7.3).

Random blocks of BC1, BC2, BC3, BC4, BC5 and BC7 (each BC7 mode forced in
turn, plus fully random bytes), decoded with Pillow's BCn decoder as the
reference. Output lines:  <format> <block hex> <16 RGBA8 texels hex>
BC4 is written as (r, 0, 0, 255), BC5 as (r, g, 0, 255), as bc.hpp returns
them. Snorm variants are not covered (Pillow decodes them differently).

    python3 tools/texture/gen_bc_vectors.py > tests/gpu/texture/bc_vectors.txt
"""
import random
import sys

from PIL import Image

PER_KIND = 64


def decode(n, mode, data):
    im = Image.frombytes(mode, (4, 4), data, "bcn", n)
    out = bytearray()
    for px in im.getdata() if not hasattr(im, "get_flattened_data") else im.get_flattened_data():
        if mode == "L":
            out += bytes([px, 0, 0, 255])
        elif mode == "RGB":
            out += bytes([px[0], px[1], 0, 255])
        else:
            out += bytes(px)
    return bytes(out)


def main():
    rng = random.Random(0x7C3)
    lines = []

    def emit(name, n, mode, block):
        lines.append(f"{name} {block.hex()} {decode(n, mode, block).hex()}")

    for _ in range(PER_KIND):
        b = bytes(rng.randrange(256) for _ in range(8))
        emit("BC1", 1, "RGBA", b)
        # The other colour order (three-colour block <-> four-colour block).
        emit("BC1", 1, "RGBA", b[2:4] + b[0:2] + b[4:])
        emit("BC4", 4, "L", b)
    for _ in range(PER_KIND):
        b = bytes(rng.randrange(256) for _ in range(16))
        emit("BC2", 2, "RGBA", b)
        emit("BC3", 3, "RGBA", b)
        emit("BC3", 3, "RGBA", bytes([b[1], b[0]]) + b[2:])
        emit("BC5", 5, "RGB", b)
        emit("BC7", 7, "RGBA", b)
    for mode in range(8):
        for _ in range(PER_KIND):
            v = rng.getrandbits(128)
            v = (v >> (mode + 1) << (mode + 1)) | (1 << mode)
            emit("BC7", 7, "RGBA", v.to_bytes(16, "little"))
    sys.stdout.write("# Generated by tools/texture/gen_bc_vectors.py (reference: Pillow's BCn decoder).\n")
    sys.stdout.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
