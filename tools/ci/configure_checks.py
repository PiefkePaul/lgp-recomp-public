#!/usr/bin/env python3
"""Export the results of CMake configure checks as an initial-cache script.

Dependencies such as SDL3 and libopus run hundreds of check_include_file /
check_c_source_compiles / check_symbol_exists probes while configuring. Each
probe is a try_compile; with MSVC on Windows that is ~1.2 s apiece. CMake skips
a probe whose result variable is already in the cache, so a CI job can save the
results of one configure and pass them to the next one with `cmake -C <file>`.

Only cache entries written by CMake's check modules are exported. They are
recognised by the help string CMake gives them ("Have include X",
"Have function X", "Have symbol X", "Have library X", "Test X", "Result of
TRY_COMPILE"/"Result of TRY_RUN"). The caller must key the saved file on the
compiler (version) and on the dependency pins, otherwise stale results leak
into a different toolchain.

Usage: configure_checks.py <CMakeCache.txt> <out.cmake>
"""

import re
import sys

HELP_PREFIXES = (
    "Have include ",
    "Have includes ",
    "Have function ",
    "Have symbol ",
    "Have library ",
    "Have variable ",
    "Test ",
    "Result of TRY_COMPILE",
    "Result of TRY_RUN",
    "Result of TEST_BIG_ENDIAN",
)
ENTRY = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):(INTERNAL|BOOL|STRING)=(.*)$")


def cmake_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def export(cache_path: str) -> list[str]:
    lines = []
    help_text = ""
    with open(cache_path, encoding="utf-8", errors="replace") as cache:
        for raw in cache:
            line = raw.rstrip("\n")
            if line.startswith("//"):
                help_text = line[2:]
                continue
            match = ENTRY.match(line)
            if match and help_text.startswith(HELP_PREFIXES):
                name, kind, value = match.groups()
                lines.append(f"set({name} {cmake_quote(value)} CACHE {kind} {cmake_quote(help_text)})")
            help_text = ""
    return lines


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    lines = export(sys.argv[1])
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
        out.write("# Generated by tools/ci/configure_checks.py; configure check results.\n")
        out.write("\n".join(lines) + "\n")
    print(f"configure_checks: {len(lines)} check results -> {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
