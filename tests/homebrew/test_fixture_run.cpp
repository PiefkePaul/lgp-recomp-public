// P2.8 acceptance: a homebrew fixture (devkitA64/libnx NSO or NRO) runs
// recompiled with the same end state as under the oracle.
//
// usage: lgp_fixture_run_<name> <module> [--oracle] [--write-expected FILE] [--expected FILE] [--trace]
//
//   --oracle          run the module under Unicorn first (needs a build with
//                     LGP_FIXTURE_ORACLE), then recompiled, and compare
//   --write-expected  write the oracle's end state as text (for builds without
//                     Unicorn, i.e. WebAssembly)
//   --expected        compare the recompiled run with such a file
//
// Both executors run on the same lgp::rt::Kernel setup (fixture_process.hpp);
// the oracle is installed as the indirect resolver for every address, the
// recompiled run uses the dispatch table generated by lgp_lift.
#include <cstdio>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>

#include "fixture_process.hpp"
#include "lgp/runtime/dispatch.hpp"
#include "lgp/runtime/system.hpp"

#if LGP_FIXTURE_ORACLE
#include "unicorn_guest.hpp"
#endif

extern const lgp::LiftedEntry lgp_lifted_entries[];
extern const size_t lgp_lifted_entries_count;

namespace {

using namespace lgp_fixture;

#if LGP_FIXTURE_ORACLE
lgp::LiftedFn resolve_oracle(uint64_t) { return &run_under_unicorn; }
#endif

void print_state(const char* name, const EndState& s) {
    std::printf("  %s: exit %s, %zu debug line(s), %zu block(s)\n", name, s.exit.c_str(), s.debug_output.size(),
                s.blocks.size());
    for (const std::string& line : s.debug_output) std::printf("    debug: %s\n", line.c_str());
}

bool read_file(const std::string& path, std::string* out) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return false;
    std::ostringstream ss;
    ss << f.rdbuf();
    *out = ss.str();
    return true;
}

// Line by line, so a failure names what differs.
bool compare_text(const std::string& expected, const std::string& actual) {
    if (expected == actual) return true;
    std::istringstream e(expected), a(actual);
    std::string el, al;
    int line = 1;
    for (;; ++line) {
        const bool he = static_cast<bool>(std::getline(e, el));
        const bool ha = static_cast<bool>(std::getline(a, al));
        if (!he && !ha) break;
        if (!he) el = "<none>";
        if (!ha) al = "<none>";
        if (el != al) std::printf("  line %d: expected '%s'\n          actual   '%s'\n", line, el.c_str(), al.c_str());
    }
    return false;
}

}  // namespace

int main(int argc, char** argv) {
    std::string module_path, write_expected, expected_path;
    bool oracle = false;
    RunOptions options;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--oracle") {
            oracle = true;
        } else if (a == "--write-expected" && i + 1 < argc) {
            write_expected = argv[++i];
        } else if (a == "--expected" && i + 1 < argc) {
            expected_path = argv[++i];
        } else if (a == "--trace") {
            options.trace_svcs = true;
        } else if (module_path.empty() && a[0] != '-') {
            module_path = a;
        } else {
            std::fprintf(stderr, "usage: %s <module> [--oracle] [--write-expected FILE] [--expected FILE] [--trace]\n",
                         argv[0]);
            return 2;
        }
    }
    if (module_path.empty() || (!oracle && expected_path.empty()) || (!write_expected.empty() && !oracle)) {
        std::fprintf(stderr, "%s: need a module and --oracle and/or --expected\n", argv[0]);
        return 2;
    }

    const lgp::recomp::Module module = load_fixture(module_path);
    std::printf("%s: %zu bytes at 0x%llx, entry +0x%llx, %zu recompiled functions\n", module_path.c_str(),
                module.image.size(), static_cast<unsigned long long>(kModuleBase),
                static_cast<unsigned long long>(module.entry_offset), lgp_lifted_entries_count);
    bool ok = true;

    std::string oracle_text;
    EndState oracle_state;
    if (oracle) {
#if LGP_FIXTURE_ORACLE
        lgp::rt::set_indirect_resolver(&resolve_oracle);
        oracle_state = run_fixture(module, options);
        lgp::rt::set_indirect_resolver(nullptr);
        print_state("unicorn", oracle_state);
        oracle_text = to_text(oracle_state);
        if (!write_expected.empty()) {
            std::ofstream f(write_expected, std::ios::binary);
            f << oracle_text;
            if (!f) {
                std::printf("  FAIL cannot write %s\n", write_expected.c_str());
                ok = false;
            }
        }
#else
        std::fprintf(stderr, "%s: built without the Unicorn oracle\n", argv[0]);
        return 2;
#endif
    }

    lgp::rt::register_functions(lgp_lifted_entries, lgp_lifted_entries_count);
    const EndState recompiled = run_fixture(module, options);
    print_state("recompiled", recompiled);
    const std::string unresolved = lgp::rt::unresolved_config();
    if (!unresolved.empty()) {
        std::printf("  FAIL indirect branches to unknown targets:\n%s", unresolved.c_str());
        ok = false;
    }
    // Fixtures that check themselves report it in a debug line.
    for (const std::string& line : recompiled.debug_output)
        if (line.find("FAIL") != std::string::npos) {
            std::printf("  FAIL the fixture reports: %s\n", line.c_str());
            ok = false;
        }
    if (recompiled.exit != "ExitProcess") {
        std::printf("  FAIL the process did not end with svcExitProcess\n");
        ok = false;
    }

    if (oracle && !compare(oracle_state, recompiled, "unicorn", "recompiled")) {
        std::printf("  FAIL recompiled end state differs from unicorn\n");
        ok = false;
    }
    if (!expected_path.empty()) {
        std::string expected;
        if (!read_file(expected_path, &expected)) {
            std::printf("  FAIL cannot read %s\n", expected_path.c_str());
            ok = false;
        } else if (!compare_text(expected, to_text(recompiled))) {
            std::printf("  FAIL recompiled end state differs from %s\n", expected_path.c_str());
            ok = false;
        }
    }
    std::printf(ok ? "identical end state\n" : "FAILED\n");
    return ok ? 0 : 1;
}
