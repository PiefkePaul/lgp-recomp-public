#!/usr/bin/env python3
"""Assembles thread_programs.s into thread_program_code.hpp (P3.2 test programs).

Needs llvm-mc, llvm-objcopy and llvm-nm in PATH. Run after editing the .s and
commit both files; the build only uses the generated header, so CI does not
need LLVM tools.

Usage: python3 tests/runtime/gen_thread_programs.py
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "thread_programs.s")
OUT = os.path.join(HERE, "thread_program_code.hpp")


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def main():
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "p.o")
        binf = os.path.join(tmp, "p.bin")
        run("llvm-mc", "-triple=aarch64", "-filetype=obj", SRC, "-o", obj)
        run("llvm-objcopy", "-O", "binary", "--only-section=.text", obj, binf)
        with open(binf, "rb") as f:
            text = f.read()
        syms = []
        for line in run("llvm-nm", "--defined-only", obj).splitlines():
            addr, kind, name = line.split()
            if kind in "Tt" and not name.startswith(".L") and not name.startswith("$"):
                syms.append((int(addr, 16), name))
        dis = run("llvm-objdump", "-d", "--no-show-raw-insn", obj)
    syms.sort()
    asm = {}
    for line in dis.splitlines():
        parts = line.split(":", 1)
        if len(parts) == 2 and parts[0].strip() and all(c in "0123456789abcdef" for c in parts[0].strip()):
            asm[int(parts[0].strip(), 16)] = " ".join(parts[1].split())
    if len(text) % 4:
        sys.exit("text size not a multiple of 4")
    names = {a: n for a, n in syms}
    out = [
        "// Generated by gen_thread_programs.py from thread_programs.s. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace lgp_test {",
        "",
        "struct ThreadFunction {",
        "    const char* name;",
        "    uint32_t offset;  // from the start of kThreadText",
        "    uint32_t size;    // bytes, up to the next function",
        "};",
        "",
        "inline constexpr uint32_t kThreadText[] = {",
    ]
    for off in range(0, len(text), 4):
        if off in names:
            out.append(f"    // {names[off]}")
        word = int.from_bytes(text[off:off + 4], "little")
        out.append(f"    0x{word:08x},  // {off:04x}: {asm.get(off, '?')}")
    out.append("};")
    out.append("")
    out.append("inline constexpr ThreadFunction kThreadFunctions[] = {")
    for i, (addr, name) in enumerate(syms):
        end = syms[i + 1][0] if i + 1 < len(syms) else len(text)
        out.append(f'    {{"{name}", 0x{addr:x}, 0x{end - addr:x}}},')
    out.append("};")
    out.append("")
    out.append("}  // namespace lgp_test")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
