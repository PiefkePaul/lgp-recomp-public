// Host tool: lifts the multi-thread test programs (thread_program_code.hpp)
// with the P2.3 lifter, one C++ function per guest function, plus a table
// from guest address to lifted function (the tests' indirect resolver).
// Usage: lgp_lift_thread_programs <out.cpp>
#include <cstdio>
#include <fstream>
#include <string>
#include <vector>

#include "kernel_program_code.hpp"
#include "lgp/recomp/lifter.hpp"
#include "thread_program_code.hpp"

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <out.cpp>\n", argv[0]);
        return 2;
    }
    using namespace lgp_test;
    const uint64_t end = kProgramBase + sizeof(kThreadText);
    std::vector<uint64_t> entries;
    for (const ThreadFunction& f : kThreadFunctions)
        entries.push_back(kProgramBase + f.offset);
    lgp::recomp::LiftOptions options;
    options.name_prefix = "lgp_thr_";
    options.precise_fault_pc = true;
    lgp::recomp::Lifter lifter(
        [&](uint64_t va, uint32_t& insn) {
            if (va < kProgramBase || va >= end || (va & 3) != 0)
                return false;
            insn = kThreadText[(va - kProgramBase) / 4];
            return true;
        },
        entries, options);

    std::string out =
        "// Generated by lgp_lift_thread_programs from tests/runtime/thread_program_code.hpp. Do not edit.\n"
        "#include <cstddef>\n"
        "#include \"lgp/lifted/lifted.hpp\"\n"
        "#include \"lifted_table.hpp\"\n\n";
    out += lifter.declarations();
    std::string table = "extern const lgp_test::LiftedEntry kLiftedThreadFunctions[] = {\n";
    for (const ThreadFunction& f : kThreadFunctions) {
        lgp::recomp::LiftFunction fn;
        fn.entry = kProgramBase + f.offset;
        fn.blocks.push_back({fn.entry, fn.entry + f.size});
        lgp::recomp::LiftStats stats;
        out += lifter.lift(fn, stats);
        out += "\n";
        if (stats.unsupported != 0) {
            std::fprintf(stderr, "%s: %llu unsupported instructions\n", f.name,
                         static_cast<unsigned long long>(stats.unsupported));
            return 1;
        }
        table += "    {0x" + [&] {
            char buf[24];
            std::snprintf(buf, sizeof(buf), "%llx", static_cast<unsigned long long>(fn.entry));
            return std::string(buf);
        }() + "ull, &" + lifter.function_name(fn.entry) + "},\n";
    }
    table += "};\nextern const size_t kLiftedThreadFunctionCount = " + std::to_string(std::size(kThreadFunctions)) +
             ";\n";
    std::ofstream file(argv[1]);
    file << out << table;
    return file.good() ? 0 : 1;
}
