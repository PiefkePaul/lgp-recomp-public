#!/usr/bin/env python3
"""Turns own test shaders (.hex from tools/shader/assemble_test_shader.py)
into a C header for the AArch64 guest test programs.

usage: shaders_to_header.py out.h name=shader.hex[:nvnheader] ...

":nvnheader" puts the 0x30-byte NVN code header (magic 0x12345678, then
zeros) in front of the SPH, as BNSH stores graphics stages
(docs/knowledge/bnsh-format.md); the HLE must accept both forms.
Compute shaders (no SPH, no header) also get <name>Info[4] = workgroup
x, y, z and shared memory bytes from their "compute" line.
"""
import sys


def read_hex(path):
    out = bytearray()
    info = None
    with open(path) as f:
        for line in f:
            line = line.split('#', 1)[0].split()
            if not line:
                continue
            if line[0] == 'compute':
                info = [int(v, 0) for v in line[1:5]]
            elif line[0] == 'sph':
                for w in line[1:]:
                    out += int(w, 16).to_bytes(4, 'little')
            else:
                out += int(line[0], 16).to_bytes(8, 'little')
    return bytes(out), info


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    lines = ['// Generated by tests/nvn/guest/shaders_to_header.py. Own test shaders, no game code.', '#pragma once', '']
    for arg in sys.argv[2:]:
        name, spec = arg.split('=', 1)
        # The flag follows the last ':'; a Windows drive letter ("D:/...") is not one.
        path, flag = spec, ''
        head, sep, tail = spec.rpartition(':')
        if sep and tail == 'nvnheader':
            path, flag = head, tail
        data, info = read_hex(path)
        if info is not None:
            lines.append(f'static const unsigned {name}Info[4] = {{{", ".join(map(str, info))}}};')
        if flag == 'nvnheader':
            data = (0x12345678).to_bytes(4, 'little') + bytes(0x2C) + data
        lines.append(f'alignas(256) static const unsigned char {name}[{len(data)}] = {{')
        for i in range(0, len(data), 16):
            lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        lines.append('};')
        lines.append('')
    with open(sys.argv[1], 'w') as f:
        f.write('\n'.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
